def beard(spans, pat="HJHh", dark_from=19, bottom=None):
    out=[]
    for y,(x0,x1) in spans.items():
        s="O"
        for x in range(x0+1,x1):
            c=pat[x%len(pat)]
            if x>=dark_from: c={'J':'H','H':'h','h':'k'}[c] if c in 'JHh' else c
            if x==x1-1: c='k'
            if bottom and y>=bottom and c=='J': c='H'
            s+=c
        out.append((y,x0,s+"O"))
    return out
